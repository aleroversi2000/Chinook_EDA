
-- Top 10 customers by total spend and their share of overall revenue
SELECT c.CustomerId, c.FirstName, c.LastName,
       ROUND(SUM(i.Total), 2) AS total_spent,
       ROUND(100.0 * SUM(i.Total) / (SELECT SUM(Total) FROM Invoice), 2) AS pct_of_total
FROM Customer c
JOIN Invoice i ON i.CustomerId = c.CustomerId
GROUP BY c.CustomerId
ORDER BY total_spent DESC
LIMIT 10;


-- Customers with total expense higher than average expense
SELECT c.FirstName AS name, 
c.LastName AS surname,
SUM(i.Total) AS total_expense
FROM Customer c
JOIN Invoice i 
ON i.CustomerId = c.CustomerId
GROUP BY c.CustomerId
HAVING SUM(i.Total) > (
    SELECT AVG(total_client)
    FROM (
        SELECT SUM(Total) AS total_client
        FROM Invoice
        GROUP BY CustomerId
    )
) ORDER BY total_expense DESC;


-- Customers with no invoices
SELECT c.CustomerId,
c.FirstName AS name,
c.LastName AS surname
FROM Customer c
LEFT JOIN Invoice i ON i.CustomerId = c.CustomerId
WHERE i.InvoiceId IS NULL;


-- Monthly revenue
SELECT strftime('%Y', InvoiceDate) AS year,
       strftime('%m', InvoiceDate) AS month,
       ROUND(SUM(Total), 2) AS revenues
FROM Invoice
GROUP BY year, month
ORDER BY year, month;


-- Countries with average invoice above overall average
SELECT BillingCountry AS country,
       ROUND(AVG(Total), 2) AS avg_invoice
FROM Invoice
GROUP BY BillingCountry
HAVING AVG(Total) > (SELECT AVG(Total) FROM Invoice)
ORDER BY avg_invoice DESC;


-- Revenue per genre & share of total sales
SELECT g.Name AS genre,
       ROUND(SUM(il.UnitPrice * il.Quantity), 2) AS revenue,
       ROUND(100.0 * SUM(il.UnitPrice * il.Quantity)
             / (SELECT SUM(UnitPrice * Quantity) FROM InvoiceLine), 2) AS pct_of_total
FROM InvoiceLine il
JOIN Track t ON t.TrackId = il.TrackId
JOIN Genre g ON g.GenreId = t.GenreId
GROUP BY g.GenreId
ORDER BY revenue DESC;


-- Top 5 artists by n. of tracks sold
SELECT ar.Name AS artist,
       SUM(il.Quantity) AS tracks_sold
FROM InvoiceLine il
JOIN Track t ON t.TrackId = il.TrackId
JOIN Album al ON al.AlbumId = t.AlbumId
JOIN Artist ar ON ar.ArtistId = al.ArtistId
GROUP BY ar.ArtistId
ORDER BY tracks_sold DESC
LIMIT 5;

-- Albums with more than 10 tracks
SELECT al.Title AS album,
       COUNT(*) AS track_count
FROM Album al
JOIN Track t ON t.AlbumId = al.AlbumId
GROUP BY al.AlbumId
HAVING COUNT(*) > 10
ORDER BY track_count DESC;


-- Best-selling genre per country
WITH sales AS (
    SELECT i.BillingCountry AS country,
           g.Name AS genre,
           SUM(il.Quantity) AS tracks
    FROM Invoice i
    JOIN InvoiceLine il ON il.InvoiceId = i.InvoiceId
    JOIN Track t ON t.TrackId = il.TrackId
    JOIN Genre g ON g.GenreId = t.GenreId
    GROUP BY country, genre
),
ranking AS (
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY country ORDER BY tracks DESC) AS rank_pos
    FROM sales
)
SELECT country, genre, tracks
FROM ranking
WHERE rank_pos = 1
ORDER BY country;


-- Revenue generated by the customers of each support rep
SELECT e.FirstName AS name,
e.LastName AS surname,
ROUND(SUM(i.Total), 2) AS revenue
FROM Employee e
JOIN Customer c ON c.SupportRepId = e.EmployeeId
JOIN Invoice i  ON i.CustomerId = c.CustomerId
GROUP BY e.EmployeeId
ORDER BY revenue DESC;



